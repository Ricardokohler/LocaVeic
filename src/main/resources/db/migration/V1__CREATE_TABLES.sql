    CREATE TABLE TB_CLIENTS(
        ID BIGSERIAL PRIMARY KEY,
        NAME VARCHAR(255) NOT NULL,
        PHONE VARCHAR(255) NOT NULL,
        CPF VARCHAR(255) NOT NULL UNIQUE,
        EMAIL VARCHAR(255) NOT NULL UNIQUE,
        ADDRESS TEXT NOT NULL
    );

    CREATE TABLE TB_CONSULTANTS(
        ID BIGSERIAL PRIMARY KEY,
        NAME VARCHAR(255) NOT NULL,
        PHONE VARCHAR(255) NOT NULL,
        CPF VARCHAR(255) NOT NULL UNIQUE,
        EMAIL VARCHAR(255) NOT NULL UNIQUE,
        ADDRESS TEXT NOT NULL
    );

    CREATE TABLE TB_MANAGERS(
        ID BIGSERIAL PRIMARY KEY,
        NAME VARCHAR(255) NOT NULL,
        PHONE VARCHAR(255) NOT NULL,
        CPF VARCHAR(255) NOT NULL UNIQUE,
        EMAIL VARCHAR(255) NOT NULL UNIQUE,
        ADDRESS TEXT NOT NULL
    );

    CREATE TABLE TB_VEHICLES(
        ID BIGSERIAL PRIMARY KEY,

        MODEL VARCHAR(255) NOT NULL,
        BRAND VARCHAR(255) NOT NULL
    );


    CREATE TABLE TB_ORDERS(
        ID BIGSERIAL PRIMARY KEY,

        START_TIME TIMESTAMP NOT NULL,
        FINAL_TIME DATE,
        DISCOUNT DOUBLE PRECISION,
        FINAL_AMOUNT DOUBLE PRECISION,

        ID_CLIENT BIGINT,
        ID_CONSULTANT BIGINT,
        ID_MANAGER BIGINT,
        ID_VEHICLE BIGINT,

        FOREIGN KEY(ID_CLIENT) REFERENCES TB_CLIENTS(ID),
        FOREIGN KEY(ID_CONSULTANT) REFERENCES TB_CONSULTANTS(ID),
        FOREIGN KEY(ID_MANAGER) REFERENCES TB_MANAGERS(ID),
        FOREIGN KEY(ID_VEHICLE) REFERENCES TB_VEHICLES(ID)
    );
